# 飼料放在薄冰上和周圍（每 0.25 公尺）：看有沒有因此跳過某一步的捷徑。道具 0＝香蕉皮、1＝飼料
# 用法同其他幾支：python3 levels/ice/tests/levels/s_thin.py > levels/ice/tests/levels/tables/feed_on_thin.txt
from lv import *
def around(c,r):
    return [g for g in grid('E',c[0]-r-0.75,c[0]+r+0.75,c[1]-r-0.75,c[1]+r+0.75,0.25) if math.hypot(g[1]-c[0],g[2]-c[1])<=r+0.75]
def go(stage,title,c,r,fixed,name):
    print('== 第 %s 關 薄冰 (%.2f,%.2f)：%s'%(stage,c[0],c[1],title)); gridmap(stage,around(c,r),fixed,1,name)
# 第 3 關：薄冰甲（家豪腳下）、薄冰乙
for c,r,n in [((3.0,2.4),1.6,'a'),((5.1,-5.15),1.1,'b')]:
    go(13,'只放飼料（規格允許過關）',c,r,[],'t13_0'+n)
    go(13,'香蕉皮 (1.15,-6.3)＋飼料',c,r,[(0,('B',1.15,-6.3))],'t13_1'+n)
