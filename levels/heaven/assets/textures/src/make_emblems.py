def seg_dist(px, py, ax, ay, bx, by):
    dx, dy = bx - ax, by - ay
    l2 = dx * dx + dy * dy
    t = 0.0 if l2 == 0 else max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / l2))
    qx, qy = ax + dx * t, ay + dy * t
    return math.hypot(px - qx, py - qy)


def render(e):
    segs = []
    for ln in e["lines"]:
        for i in range(1, len(ln)):
            segs.append((ln[i - 1][0], ln[i - 1][1], ln[i][0], ln[i][1]))
    k = SIZE / 100.0
    rows = []
    for j in range(SIZE):
        row = bytearray([0])
        y = (j + 0.5) / k
        for i in range(SIZE):
            x = (i + 0.5) / k
            d = 1e9
            for (ax, ay, bx, by) in segs:
                if min(ax, bx) - 4 <= x <= max(ax, bx) + 4 and min(ay, by) - 4 <= y <= max(ay, by) + 4:
                    d = min(d, seg_dist(x, y, ax, ay, bx, by) - W / 2)
            for (cx, cy, r) in e["dots"]:
                d = min(d, math.hypot(x - cx, y - cy) - r)
            a = max(0.0, min(1.0, 0.5 - d * k))
            row += bytes((GOLD[0], GOLD[1], GOLD[2], int(a * 255)))
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(t, data):
        c = struct.pack(">I", len(data)) + t + data
        return c + struct.pack(">I", zlib.crc32(t + data) & 0xffffffff)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


